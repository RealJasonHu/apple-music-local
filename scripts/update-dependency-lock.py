#!/usr/bin/env python3
"""Maintainer-only lock refresh, using explicit versions and public PyPI metadata.

Run with the pinned Python after intentionally editing version lines in
requirements.lock.txt. It selects artifacts compatible with macOS 14 arm64 /
CPython 3.12 and pins their hashes; ordinary builds never run this script.
"""
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import re
import urllib.request

from pip._vendor.packaging.tags import compatible_tags, cpython_tags, mac_platforms
from pip._vendor.packaging.utils import parse_wheel_filename

ROOT = Path(__file__).resolve().parents[1]
PLATFORMS = list(mac_platforms(version=(14, 0), arch="arm64"))
TAGS = list(cpython_tags(python_version=(3, 12), abis=["cp312"], platforms=PLATFORMS))
TAGS += list(compatible_tags(python_version=(3, 12), interpreter="cp312", platforms=PLATFORMS))
RANKS = {tag: rank for rank, tag in enumerate(TAGS)}
BUILDS = [("setuptools", "84.0.0"), ("wheel", "0.48.0"), ("packaging", "26.3"),
          ("zstandard", "0.25.0")]  # Build-only: read the upstream Python license archive.


def artifact(spec):
    name, version = spec
    request = urllib.request.Request(f"https://pypi.org/pypi/{name}/{version}/json",
                                     headers={"User-Agent": "AppleMusicLocal-lock/1"})
    with urllib.request.urlopen(request, timeout=60) as response:
        release = json.load(response)
    wheels = []
    for item in release["urls"]:
        if item["packagetype"] != "bdist_wheel" or item.get("yanked"):
            continue
        _, _, _, tags = parse_wheel_filename(item["filename"])
        ranks = [RANKS[tag] for tag in tags if tag in RANKS]
        if ranks:
            wheels.append((min(ranks), item["filename"], item))
    if wheels:
        selected = min(wheels, key=lambda item: item[:2])[2]
    else:
        sources = [item for item in release["urls"]
                   if item["packagetype"] == "sdist" and not item.get("yanked")]
        if len(sources) != 1:
            raise RuntimeError(f"Review artifact selection for {name}=={version}")
        selected = sources[0]
    return {"name": name, "version": version, "filename": selected["filename"],
            "url": selected["url"], "sha256": selected["digests"]["sha256"],
            "kind": selected["packagetype"], "metadata_url": request.full_url}


def write_lock(path, packages):
    lines = ["# Exact PyPI artifacts selected for CPython 3.12 / macOS 14+ arm64.",
             "# Generated by scripts/update-dependency-lock.py; review version edits before refreshing."]
    for package in packages:
        lines.append(f"{package['name']}=={package['version']} --hash=sha256:{package['sha256']}")
    path.write_text("\n".join(lines) + "\n")


def main():
    versions = re.findall(r"^([A-Za-z0-9_.-]+)==([^\s]+)",
                          (ROOT / "requirements.lock.txt").read_text(), re.M)
    if not versions or len(versions) != len(set(name for name, _ in versions)):
        raise RuntimeError("Invalid or duplicated requirement pins")
    with ThreadPoolExecutor(max_workers=8) as pool:
        runtime = list(pool.map(artifact, versions))
        build = list(pool.map(artifact, BUILDS))
    manifest = {
        "schema": 1,
        "target": "CPython 3.12, macOS 14+, arm64",
        "python": {
            "version": "3.12.14", "build": "20260901",
            "filename": "cpython-3.12.14+20260901-aarch64-apple-darwin-install_only_stripped.tar.gz",
            "url": "https://github.com/astral-sh/python-build-standalone/releases/download/20260901/cpython-3.12.14%2B20260901-aarch64-apple-darwin-install_only_stripped.tar.gz",
            "sha256": "81a359f1cfadd4da11766534c5913791cea55f26e1bb902cacd2a531bb1e4b2b",
            "metadata_url": "https://api.github.com/repos/astral-sh/python-build-standalone/releases/tags/20260901"
        },
        "python_licenses": {
            "filename": "cpython-3.12.14+20260901-aarch64-apple-darwin-pgo+lto-full.tar.zst",
            "url": "https://github.com/astral-sh/python-build-standalone/releases/download/20260901/cpython-3.12.14%2B20260901-aarch64-apple-darwin-pgo%2Blto-full.tar.zst",
            "sha256": "dbefa04d4107b449e17022f9c78d3eacbd37a1aa8c166c6220dbd95addf3f318",
            "metadata_url": "https://api.github.com/repos/astral-sh/python-build-standalone/releases/tags/20260901"
        },
        "runtime_packages": runtime, "build_packages": build
    }
    (ROOT / "scripts/dependencies.json").write_text(json.dumps(manifest, indent=2) + "\n")
    write_lock(ROOT / "requirements.lock.txt", runtime)
    write_lock(ROOT / "scripts/build-requirements.lock.txt", build)
    print(f"Pinned {len(runtime)} runtime and {len(build)} build artifacts.")


if __name__ == "__main__":
    main()
